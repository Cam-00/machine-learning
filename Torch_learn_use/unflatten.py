import torch

x = torch.randn([3, 6])
print(x)
print(x.untyped_storage().data_ptr())
y = x.unflatten(-1, (-1, 2))
print(y)  # 将最后一维的列扩张为3行2列, 奇数下标为第一列，偶数下表为第二列
print(y.untyped_storage().data_ptr())  # x 与 y 共享内存
y[0][0][1] = 8
print(x)
print(y)

